<?php
require_once __DIR__.'/../app/agent/schema_validator.php';
require_once __DIR__.'/../app/agent/tool_registry.php';
require_once __DIR__.'/../app/agent/execution_store.php';
require_once __DIR__.'/../app/agent/loop/state.php';
function invocation_contract_assert(bool $ok,string $message):void{if(!$ok)throw new RuntimeException($message);}
$run='invocation_contract_'.bin2hex(random_bytes(6));$call='call_rejected_'.bin2hex(random_bytes(6));
$meta=lac_tool_catalog()['python_dataframe'];
$args=['data'=>[['score'=>80],['score'=>90]],'operation'=>'filter','value'=>80];
$validation=lac_tool_validate_arguments_result('python_dataframe',$args,$meta);
invocation_contract_assert(empty($validation['valid']),'Missing dataframe column must fail semantic preflight.');
invocation_contract_assert(($validation['stage']??'')==='semantic_validation','Semantic errors must be classified separately from schema errors.');
$stored=lac_invocation_reject($run,$call,'python_dataframe',$args,$validation);
$record=lac_invocation_get($run,$call);
invocation_contract_assert(!empty($record),'Rejected invocation must be persisted in the ledger.');
invocation_contract_assert(($record['state']??'')==='REJECTED','Pre-execution rejection must not be recorded as FAILED.');
invocation_contract_assert(($record['execution_started']??true)===false,'Rejected invocation must prove execution_started=false.');
invocation_contract_assert(empty($record['execution_id']),'Rejected invocation must not create an execution ID.');
invocation_contract_assert(empty($record['attempts']),'Rejected invocation must not create an execution attempt.');
$state=lac_agent_loop_execution_state($run,[],[['name'=>'python_dataframe']]);
invocation_contract_assert(($state['summary']['rejected']??0)===1,'Runtime state must include rejected invocations from the ledger.');
invocation_contract_assert(($state['summary']['committed']??0)===0,'Rejected invocations must not count as committed.');
$listed=lac_invocation_list_by_run($run);
invocation_contract_assert(count($listed)===1,'Run-level ledger query must include rejected invocation.');
$unknownCall='call_interrupted_'.bin2hex(random_bytes(5));
lac_execution_write($run,$unknownCall,['tool'=>'python_dataframe','state'=>'EXECUTING','execution_id'=>'exec_interrupted','execution_started'=>true,'history'=>[['state'=>'EXECUTING','at'=>date(DATE_ATOM)]]]);
$reconciled=lac_invocation_reconcile($run);
$unknownRecord=lac_invocation_get($run,$unknownCall);
invocation_contract_assert(($unknownRecord['state']??'')==='UNKNOWN','Interrupted non-committed execution must reconcile to UNKNOWN.');
invocation_contract_assert(($unknownRecord['execution_committed']??false)===false,'Reconciliation must never infer commit.');
@unlink(lac_execution_dir().'/'.lac_execution_key($run,$unknownCall).'.json');
@unlink(lac_execution_dir().'/'.lac_execution_key($run,$unknownCall).'.lock');
@unlink(lac_execution_dir().'/'.lac_execution_key($run,$call).'.json');
@unlink(lac_execution_dir().'/'.lac_execution_key($run,$call).'.lock');
echo "PASS: structured semantic rejection is durable, has no execution attempt, and is synchronized to runtime state\n";
